"""Measure what each acoustic scene does to the SAME line, so 'different worlds' is evidence, not taste.

Run: .venv/Scripts/python tools/scene_report.py   -> docs/SCENE_REPORT.md + probe_out/scenes/*.wav
Per scene: occupied band (5th-95th percentile of spectral energy), spectral centroid, noise floor between words
(dBFS, 10th percentile of 20 ms frames), crest factor (peak/RMS: compression), and a reverb proxy (energy in the
300 ms after the voice stops, relative to the voice).
"""
import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from ncc import scene, stingers, tts  # noqa: E402
from ncc.perform import perform  # noqa: E402
from ncc.stations import STATIONS  # noqa: E402

LINE = "Sol Brandt's car is destroyed during the race. No cause has been announced."


def metrics(x, sr, voice_len, pre):
    m = x.mean(axis=1) if x.ndim == 2 else x
    spec = np.abs(np.fft.rfft(m)) ** 2
    f = np.fft.rfftfreq(len(m), 1 / sr)
    c = np.cumsum(spec) / spec.sum()
    lo, hi = f[np.searchsorted(c, 0.05)], f[np.searchsorted(c, 0.95)]
    centroid = float((f * spec).sum() / spec.sum())
    hop = int(0.02 * sr)
    fr = np.array([np.sqrt(np.mean(m[i:i + hop] ** 2)) + 1e-9 for i in range(0, len(m) - hop, hop)])
    floor = 20 * np.log10(np.percentile(fr, 10))
    rms = np.sqrt(np.mean(m ** 2)) + 1e-9
    crest = 20 * np.log10(np.max(np.abs(m)) / rms)
    end = pre + voice_len
    tail = m[end:end + int(0.3 * sr)]
    body = m[pre:end]
    rev = 10 * np.log10((np.mean(tail ** 2) + 1e-12) / (np.mean(body ** 2) + 1e-12)) if len(tail) else -99
    return lo, hi, centroid, floor, crest, rev


def main():
    eng = tts.PiperEngine(os.path.join(ROOT, "voices"))
    outdir = os.path.join(ROOT, "probe_out", "scenes")
    os.makedirs(outdir, exist_ok=True)
    rows = []
    voice = "en_GB-alba-medium"     # one voice through every scene: the difference is the room, not the speaker
    x, sr = eng.synth(voice, perform(LINE, "news", {}).script)
    for name, p in scene.PRESETS.items():
        y = scene.render(x, sr, name, seed=3)
        pre = int(sr * p.preroll_s) + (int(sr * 0.12) if p.squelch else 0)
        tts.write_wav(os.path.join(outdir, f"{name}.wav"), y, sr)
        rows.append((name,) + metrics(y, sr, len(x), pre))
    lines = ["# Scene report (generated by tools/scene_report.py)", "",
             f"One voice ({voice}), one line, five scenes. WAVs in probe_out/scenes/.", "",
             "| scene | band 5-95% Hz | centroid Hz | floor dBFS | crest dB | tail 300 ms dB |", "|---|---|---|---|---|---|"]
    for n, lo, hi, cen, fl, cr, rv in rows:
        lines.append(f"| {n} | {lo:.0f}-{hi:.0f} | {cen:.0f} | {fl:.1f} | {cr:.1f} | {rv:.1f} |")
    lines += ["", "Stingers: " + ", ".join(f"{k} {len(stingers.get(k, sr)) / sr:.1f}s" for k in stingers.GENERATORS)]
    for k in stingers.GENERATORS:
        tts.write_wav(os.path.join(outdir, f"sting_{k}.wav"), stingers.get(k, sr), sr)
    text = "\n".join(lines) + "\n"
    with open(os.path.join(ROOT, "docs", "SCENE_REPORT.md"), "w", encoding="utf-8", newline="") as f:
        f.write(text)
    print(text)


if __name__ == "__main__":
    main()
