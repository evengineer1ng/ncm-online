"""The sonic vocabulary: short procedural stingers, one per segment.

    news          three rising FM-bell notes over a sub hit: "a bulletin"
    race_control  a two-tone PA chime with a radio key-up: "an institution speaks"
    street        a filtered whoosh into the street: "we are somewhere out there"
    garage        a ratchet and a metal tap: "the workshop"
    ident         Night City Chronicles: a low swell and a falling fifth (optional, at session start)
The Narrator has none: they are the connective tissue between programmes.

PROVENANCE: generated by this file (procedural synthesis, no samples) -- owned by the project, free to ship.
To replace one, drop `assets/stingers/<id>.wav`; it is used as-is (resampled to the voice rate).
"""
from __future__ import annotations

import os

import numpy as np

from .scene import band, db, impulse, convolve, norm, noise_pink
from .tts import read_wav


def _env(n, sr, a=0.005, d=0.4):
    t = np.arange(n) / sr
    return (np.minimum(1, t / a) * np.exp(-t / d)).astype(np.float32)


def _fm_bell(f, dur, sr, idx=2.5, ratio=1.4):
    n = int(sr * dur)
    t = np.arange(n) / sr
    mod = np.sin(2 * np.pi * f * ratio * t) * idx * np.exp(-t * 6)
    return (np.sin(2 * np.pi * f * t + mod) * _env(n, sr, 0.003, dur / 3)).astype(np.float32)


def _place(out, x, at, sr, gain=1.0):
    i = int(at * sr)
    j = min(len(out), i + len(x))
    out[i:j] += x[: j - i] * gain


def news(sr, rng):
    out = np.zeros(int(sr * 1.6), np.float32)
    for k, (f, at) in enumerate(((659.3, 0.0), (880.0, 0.16), (1318.5, 0.32))):
        _place(out, _fm_bell(f, 0.9 if k == 2 else 0.4, sr), at, sr, 0.5)
    sub = np.sin(2 * np.pi * 55 * np.arange(int(sr * 0.8)) / sr) * _env(int(sr * 0.8), sr, 0.002, 0.25)
    _place(out, sub.astype(np.float32), 0.32, sr, 0.6)
    tail = convolve(out, impulse(sr, rng, 1.1, 10, bright=2)) * 0.25
    return norm(out + tail[: len(out)]) * 0.6


def race_control(sr, rng):
    out = np.zeros(int(sr * 1.5), np.float32)
    for f, at in ((783.99, 0.05), (622.25, 0.45)):            # G5 -> D#5: the "bing-bong"
        n = int(sr * 0.9)
        t = np.arange(n) / sr
        tone = (np.sin(2 * np.pi * f * t) + 0.3 * np.sin(2 * np.pi * f * 2 * t) + 0.1 * np.sin(2 * np.pi * f * 3 * t))
        _place(out, (tone * _env(n, sr, 0.004, 0.35)).astype(np.float32), at, sr, 0.45)
    hall = convolve(out, impulse(sr, rng, 1.6, 40, early=[(90, 0.3)])) * 0.3
    out = out + hall[: len(out)]
    out = band(out, sr, 300, 3400)
    return norm(out) * 0.55


def street(sr, rng):
    n = int(sr * 1.1)
    t = np.arange(n) / sr
    x = norm(noise_pink(n, rng))
    # sweep a band from high to low: the whoosh of a car you just missed
    parts = np.array_split(np.arange(n), 12)
    out = np.zeros(n, np.float32)
    for k, idx in enumerate(parts):
        c = 4000 * (0.6 ** k) + 200
        seg = band(x, sr, c * 0.6, c * 1.6)[idx]
        out[idx] = seg
    env = np.exp(-((t - 0.45) / 0.25) ** 2)
    return norm(out * env) * 0.45


def garage(sr, rng):
    out = np.zeros(int(sr * 1.0), np.float32)
    L = int(sr * 0.45)
    tt = np.arange(L) / sr
    gate = (np.sin(2 * np.pi * 26 * tt) > 0.2).astype(np.float32)
    _place(out, band(rng.standard_normal(L).astype(np.float32), sr, 1800, 8000) * gate * np.exp(-tt * 2), 0.0, sr, 0.5)
    K = int(sr * 0.5)
    tk = np.arange(K) / sr
    tap = sum(np.sin(2 * np.pi * 1180 * r * tk) * np.exp(-tk * d) for r, d in ((1, 10), (1.73, 16), (2.61, 24)))
    _place(out, tap.astype(np.float32), 0.48, sr, 0.5)
    room = convolve(out, impulse(sr, rng, 0.7, 5, early=[(7, 0.4), (15, 0.3)], bright=3)) * 0.3
    return norm(out + room[: len(out)]) * 0.55


def ident(sr, rng):
    n = int(sr * 2.6)
    t = np.arange(n) / sr
    swell = np.minimum(1, t / 1.2) * np.exp(-np.maximum(0, t - 1.2) / 0.7)
    pad = sum(np.sin(2 * np.pi * f * t + rng.uniform(0, 6)) for f in (55, 82.4, 110, 164.8)) * swell * 0.25
    out = pad.astype(np.float32)
    _place(out, _fm_bell(1046.5, 1.0, sr, 1.5, 2.0), 1.1, sr, 0.35)
    _place(out, _fm_bell(698.5, 1.3, sr, 1.5, 2.0), 1.45, sr, 0.35)
    tail = convolve(out, impulse(sr, rng, 2.0, 20)) * 0.3
    return norm(out + tail[:n]) * 0.55


GENERATORS = {"news": news, "race_control": race_control, "street": street, "garage": garage, "ident": ident}


def get(sting_id: str, sr: int, assets: str = "", seed: int = 7) -> np.ndarray:
    """Stereo float32 stinger at `sr`."""
    path = os.path.join(assets, "stingers", sting_id + ".wav") if assets else ""
    if path and os.path.exists(path):
        x, ssr = read_wav(path)
        if ssr != sr:
            x = np.interp(np.arange(0, len(x), ssr / sr), np.arange(len(x)), x).astype(np.float32)
    else:
        x = GENERATORS[sting_id](sr, np.random.default_rng(seed))
    x = x.astype(np.float32)
    return np.stack([x, x], axis=1)
