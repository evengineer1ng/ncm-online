-- NCM Online: the Paddock (doc 44). Mostly server; a small client half since phases 4-5 (Talk prompts, live races).
--
-- The NPC motorsport world: about 60 organizations, 150 drivers, owners, managers, staff and sponsors, racing on
-- US-Eastern real time (street by night, sanctioned by day), keeping their own standings and making their own
-- news, whether or not a human is online. It never shares a grid, standing or result with a human (L224.1).
--
-- A resource of its own (feedback: new features, new mods; KB-204 showed one bad league file can block racing)
-- with its own tunables block. The schema stays in `ncm_league` (043-050) so there is one migration owner; this
-- resource waits for version 50 before it boots. Resources do NOT share memory: nothing here may call
-- `NcmEconomy`, `NcmStream` or `NcmWeather` (tools/test-paddock-host.lua lints for it). The panel page lives in
-- `ncm_world` (the PADDOCK tab); this resource answers `ncm:paddock.*` net events and streams the views.
--
-- `paddockEnabled` is a kill switch: `resources.load` includes `ncm/*`, so this directory goes live with any deploy.
