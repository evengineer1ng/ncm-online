local BY_ID = {}
local BY_SLOT = {}
for _, part in ipairs(PartsData.CATALOG) do
    BY_ID[part.id] = part
    BY_SLOT[part.slot] = BY_SLOT[part.slot] or {}
    table.insert(BY_SLOT[part.slot], part)
end

function PartsData.all()
    return PartsData.CATALOG
end

function PartsData.get(id)
    return BY_ID[id]
end

function PartsData.bySlot(slotId)
    return BY_SLOT[slotId] or {}
end

function PartsData.familyLabel(part)
    local definition = type(part) == "table" and part or BY_ID[tostring(part or "")]
    if type(definition) ~= "table" then
        return "General"
    end
    if type(definition.familyLabel) == "string" and definition.familyLabel ~= "" then
        return definition.familyLabel
    end
    return PartsData.FAMILY_LABELS[tostring(definition.family or "")] or "General"
end

function PartsData.rarityRank(rarity)
    return PartsData.RARITY_RANK[rarity] or 0
end

return PartsData