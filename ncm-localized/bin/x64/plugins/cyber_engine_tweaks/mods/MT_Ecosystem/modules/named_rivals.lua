local NamedRivals = {}

local VehiclePool = require("data/vehicle_pool")

local GAME_ROOT_REL = table.concat({ "..", "..", "..", "..", "..", ".." }, "\\")
local TWEAK_PATH = GAME_ROOT_REL .. "\\r6\\tweaks\\MT_Ecosystem\\mt_ecosystem_named_rivals.yaml"
local XL_PATH = GAME_ROOT_REL .. "\\archive\\pc\\mod\\mt_ecosystem_named_rivals.xl"
local LOC_PATH = GAME_ROOT_REL .. "\\archive\\pc\\mod\\mt_ecosystem_named_rivals\\localization\\en-us\\onscreens\\mt_ecosystem_named_rivals.json"

local XL_CONTENT = table.concat({
    "localization:",
    "  onscreens:",
    "    en-us: mt_ecosystem_named_rivals\\localization\\en-us\\onscreens\\mt_ecosystem_named_rivals.json",
    "",
}, "\n")

local function sanitizeSegment(value)
    local cleaned = tostring(value or "")
    cleaned = cleaned:gsub("[^%w_]+", "_")
    cleaned = cleaned:gsub("^_+", "")
    cleaned = cleaned:gsub("_+$", "")
    if cleaned == "" then
        cleaned = "unknown"
    end
    return cleaned
end

local function ensureDir(path)
    local probePath = path .. "\\.dir_probe"
    local probe = io.open(probePath, "a")
    if probe then
        probe:close()
        os.remove(probePath)
        return true
    end

    local attempts = {
        function()
            pcall(os.execute, 'mkdir "' .. path .. '"')
        end,
        function()
            local handle = io.popen('mkdir "' .. path .. '" 2>nul', "r")
            if handle then
                handle:close()
            end
        end,
    }

    for _, attempt in ipairs(attempts) do
        pcall(attempt)
        probe = io.open(probePath, "a")
        if probe then
            probe:close()
            os.remove(probePath)
            return true
        end
    end

    return false
end

local function ensurePathDir(filePath)
    local dir = filePath:match("^(.*)\\[^\\]+$")
    if not dir or dir == "" then
        return false
    end

    local current = ""
    for segment in dir:gmatch("[^\\]+") do
        current = (current == "") and segment or (current .. "\\" .. segment)
        if not ensureDir(current) then
            return false
        end
    end
    return true
end

local function readFile(path)
    local handle = io.open(path, "r")
    if not handle then
        return nil
    end
    local content = handle:read("*a")
    handle:close()
    return content
end

local function writeIfChanged(path, content)
    local existing = readFile(path)
    if existing == content then
        return false, true
    end
    if not ensurePathDir(path) then
        return false, false
    end

    local handle, err = io.open(path, "w")
    if not handle then
        print("[NCM/NamedRivals] Write failed on " .. tostring(path) .. ": " .. tostring(err))
        return false, false
    end
    handle:write(content)
    handle:close()
    return true, true
end

local function activeCareer()
    if not (MTE and MTE.Careers and MTE.Careers.active) then
        return nil
    end
    return MTE.Careers.active()
end

local function activeSeed()
    local career = activeCareer()
    return career and career.seed or nil
end

local function locKeyForDriver(seed, driverId)
    return string.format(
        "mt_ecosystem_rival_%s_%s_name",
        sanitizeSegment(seed),
        sanitizeSegment(driverId))
end

local function recordNameForDriver(seed, driverId)
    return string.format(
        "Character.mt_ecosystem_rival_%s_%s",
        sanitizeSegment(seed),
        sanitizeSegment(driverId))
end

local function buildPayload(career, includeUncached)
    if type(career) ~= "table" or not career.seed then
        return nil, "career_missing"
    end
    if not (MTE and MTE.Roster and MTE.Roster.eachSeededDriver) then
        return nil, "roster_iterator_missing"
    end

    local yamlLines = {
        "# Auto-generated by MT_Ecosystem named rival sync.",
        "# Each record keeps the vanilla scanner/nameplate path intact by cloning",
        "# the driver's Character.* record and only overriding the localized name.",
        "",
    }
    local locEntries = {}
    local count = 0

    MTE.Roster.eachSeededDriver(career, function(driver)
        local driverId = tostring(driver and driver.id or "")
        local driverName = tostring((driver and (driver.displayName or driver.name)) or "")
        local baseRecord = VehiclePool.getNPCSpawnKey(driver and driver.npcRecord or nil)
        if driverId == "" or driverName == "" then
            return
        end
        if type(baseRecord) ~= "string" or baseRecord == "" then
            return
        end

        local locKey = locKeyForDriver(career.seed, driverId)
        local recordName = recordNameForDriver(career.seed, driverId)
        yamlLines[#yamlLines + 1] = recordName .. ":"
        yamlLines[#yamlLines + 1] = "  $base: " .. tostring(baseRecord)
        yamlLines[#yamlLines + 1] = "  displayName: " .. locKey
        yamlLines[#yamlLines + 1] = ""
        locEntries[#locEntries + 1] = {
            primaryKey = 0,
            secondaryKey = locKey,
            femaleVariant = driverName,
            maleVariant = "",
        }
        count = count + 1
    end, includeUncached == true)

    local encoded = nil
    local ok, result = pcall(json.encode, {
        ["$type"] = "localizationPersistenceOnScreenEntries",
        entries = locEntries,
    })
    if ok then
        encoded = result
    end
    if not encoded then
        return nil, "localization_encode_failed"
    end

    return {
        tweak = table.concat(yamlLines, "\n"),
        loc = encoded,
        count = count,
    }
end

function NamedRivals.recordNameForDriver(driver, careerOrSeed)
    if type(driver) ~= "table" then
        return nil
    end
    if driver.isFaction == true then
        return nil
    end

    local driverId = tostring(driver.driverId or driver.id or "")
    if driverId == "" then
        return nil
    end

    local seed = careerOrSeed
    if type(careerOrSeed) == "table" then
        seed = careerOrSeed.seed
    end
    seed = seed or activeSeed()
    if not seed then
        return nil
    end

    return recordNameForDriver(seed, driverId)
end

function NamedRivals.getRecordForDriver(driver, careerOrSeed)
    return NamedRivals.recordNameForDriver(driver, careerOrSeed)
end

function NamedRivals.ensureForCareer(career, options)
    options = options or {}
    local payload, err = buildPayload(career, options.includeUncached == true)
    if not payload then
        return false, err or "payload_failed", 0
    end

    local changed = false
    local wrote, ok = writeIfChanged(XL_PATH, XL_CONTENT)
    changed = changed or wrote
    if not ok then
        return false, "xl_write_failed", 0
    end

    wrote, ok = writeIfChanged(TWEAK_PATH, payload.tweak)
    changed = changed or wrote
    if not ok then
        return false, "tweak_write_failed", 0
    end

    wrote, ok = writeIfChanged(LOC_PATH, payload.loc)
    changed = changed or wrote
    if not ok then
        return false, "loc_write_failed", 0
    end

    if changed then
        print(string.format(
            "[NCM/NamedRivals] Synced %d named rival records for seed %s. Restart the game to load updated TweakXL records.",
            tonumber(payload.count or 0),
            tostring(career and career.seed or "?")))
        return true, "restart_required", payload.count
    end

    return true, "up_to_date", payload.count
end

function NamedRivals.generateActiveCareer(options)
    local career = activeCareer()
    if not career then
        return false, "career_missing", 0
    end
    return NamedRivals.ensureForCareer(career, options)
end

function NamedRivals.init()
    print("[NCM/NamedRivals] Initialised.")
end

return NamedRivals