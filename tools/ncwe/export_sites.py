"""Export the Race Week Day 1 sites' barrier anchors from the open NCWE project into ncm/core/data/race_week_sites.lua.

`week.scars` lays wear behind these anchors and moves memorials onto the pavement behind the nearest one, so the
server never needs a raycast. An anchor is a placed curb barrier: its base (x, y, z) and the unit vector pointing
away from the road (ox, oy) -- the barrier's normal on the side away from the road axis through the node.

    python export_sites.py [--every 2]
"""
import argparse, math, os
from ncwe_client import Ncwe
import site_dress as S

BARRIER_ASSET = S.BARRIER.lower()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--every", type=int, default=2, help="keep every Nth barrier as an anchor")
    a = ap.parse_args()
    nodes = S.nodes()
    out = []
    with Ncwe() as n:
        for nid, nd in nodes.items():
            n.call("set_camera", look_at=[nd["x"], nd["y"], nd["z"]], pitch=-80, distance=120, wait=True)
            q = n.call("query_objects", center=[nd["x"], nd["y"], nd["z"]], radius=110, source="project",
                       kinds=["mesh"], limit=2000, show=False)
            bars = [o for o in q["objects"] if str(o.get("asset", "")).lower() == BARRIER_ASSET]
            bars.sort(key=lambda o: o.get("name", "") + "%010.3f%010.3f" % (o["position"][0], o["position"][1]))
            anchors = []
            for o in bars[::a.every]:
                x, y, z = o["position"]
                yaw = math.radians(o["rotation"]["yaw"])
                ax, ay = -math.sin(yaw), math.cos(yaw)                   # the barrier's long axis
                px, py = x - nd["x"], y - nd["y"]
                along = px * ax + py * ay
                ox, oy = px - along * ax, py - along * ay                # away from the road line through the node
                L = math.hypot(ox, oy)
                if L < 0.5:
                    continue
                anchors.append((x, y, z, ox / L, oy / L))
            if anchors:
                out.append((nid, nd["name"], anchors))
            print(nid, len(bars), "barriers ->", len(anchors), "anchors")
    path = os.path.join(S.ROOT, "ncm", "core", "data", "race_week_sites.lua")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("-- ncm-core data: data.race_week_sites\n")
        f.write("-- GENERATED by tools/ncwe/export_sites.py from ncm/ncwe/race_week_day1.ncwe; do not edit by hand.\n")
        f.write("-- Race Week Day 1 sites (IDEA-1261): curb-barrier anchors that week.scars lays wear and memorials behind.\n")
        f.write("-- anchor = { x, y, z, ox, oy }: a barrier's base and the unit vector pointing away from the road.\n")
        f.write("local Core = NcmCore\n\nCore.define(\"data.race_week_sites\", function()\n    local M = { version = \"0.1.0\" }\n    M.SITES = {\n")
        for nid, name, anchors in out:
            f.write(f"        {{ id = \"{nid}\", name = \"{name}\", anchors = {{\n")
            for x, y, z, ox, oy in anchors:
                f.write(f"            {{ x = {x:.2f}, y = {y:.2f}, z = {z:.2f}, ox = {ox:.3f}, oy = {oy:.3f} }},\n")
            f.write("        } },\n")
        f.write("    }\n    return M\nend)\n")
    print("wrote", path, sum(len(a) for _, _, a in out), "anchors over", len(out), "sites")


if __name__ == "__main__":
    main()
