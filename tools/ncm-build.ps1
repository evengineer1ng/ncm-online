<#
.SYNOPSIS
  Vendor ncm-core into every OPEN//77 resource that asks for it, idempotently.

  A resource opts in by carrying this block in its open77.lua:
      -- ncm-core:begin
      -- ncm-core:end
  The block is rewritten with `shared_script "shared/core/init.lua"` followed by one line per
  MANIFEST.lua entry, and the files are copied to <resource>/shared/core/**. Stale files under
  shared/core that are no longer part of core are removed. A second run changes nothing.

.USAGE
  powershell -NoProfile -ExecutionPolicy Bypass -File .\tools\ncm-build.ps1 [-Check]
  -Check: report what would change and exit 1 if anything would, without writing.
#>
[CmdletBinding(PositionalBinding = $false)]
param(
    [switch]$Check,
    [string]$CoreRoot,
    [string]$ResourcesRoot
)
$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
if (-not $CoreRoot)      { $CoreRoot      = Join-Path $here '..\ncm\core' }
if (-not $ResourcesRoot) { $ResourcesRoot = Join-Path $here '..\ncm\online\resources' }
$CoreRoot = (Resolve-Path $CoreRoot).Path
$ResourcesRoot = (Resolve-Path $ResourcesRoot).Path

# Parse MANIFEST.lua: quoted strings, in order.
$manifestText = [IO.File]::ReadAllText((Join-Path $CoreRoot 'MANIFEST.lua'), (New-Object Text.UTF8Encoding($false)))
$entries = [regex]::Matches($manifestText, '"([^"]+\.lua)"') | ForEach-Object { $_.Groups[1].Value }
if ($entries.Count -eq 0) { throw 'MANIFEST.lua lists no files' }
$coreFiles = @('init.lua') + $entries
foreach ($f in $coreFiles) {
    if (-not (Test-Path (Join-Path $CoreRoot $f))) { throw "MANIFEST.lua names a missing file: $f" }
}

function Same-Bytes([string]$a, [string]$b) {
    if (-not (Test-Path $a) -or -not (Test-Path $b)) { return $false }
    $ha = (Get-FileHash -LiteralPath $a -Algorithm SHA256).Hash
    $hb = (Get-FileHash -LiteralPath $b -Algorithm SHA256).Hash
    return $ha -eq $hb
}

$changes = 0
$resources = Get-ChildItem -LiteralPath $ResourcesRoot -Directory | Where-Object { Test-Path (Join-Path $_.FullName 'open77.lua') }
foreach ($res in $resources) {
    $manifestPath = Join-Path $res.FullName 'open77.lua'
    $text = [IO.File]::ReadAllText($manifestPath, (New-Object Text.UTF8Encoding($false)))
    if ($text -notmatch '(?s)-- ncm-core:begin.*?-- ncm-core:end') { continue }

    $target = Join-Path $res.FullName 'shared\core'
    # 1. Files.
    foreach ($f in $coreFiles) {
        $src = Join-Path $CoreRoot $f
        $dst = Join-Path $target ($f -replace '/', '\')
        if (-not (Same-Bytes $src $dst)) {
            $changes++
            Write-Host ("  [{0}] copy {1}" -f $res.Name, $f)
            if (-not $Check) {
                New-Item -ItemType Directory -Force -Path (Split-Path -Parent $dst) | Out-Null
                Copy-Item -LiteralPath $src -Destination $dst -Force
            }
        }
    }
    # 2. Stale files.
    if (Test-Path $target) {
        $wanted = @{}
        foreach ($f in $coreFiles) { $wanted[($f -replace '/', '\')] = $true }
        Get-ChildItem -LiteralPath $target -Recurse -File | ForEach-Object {
            $rel = $_.FullName.Substring($target.Length + 1)
            if (-not $wanted.ContainsKey($rel)) {
                $script:changes++
                Write-Host ("  [{0}] remove stale {1}" -f $res.Name, $rel)
                if (-not $Check) { Remove-Item -LiteralPath $_.FullName -Force }
            }
        }
    }
    # 3. Manifest block.
    $lines = @('-- ncm-core:begin', '-- generated by tools/ncm-build.ps1 from ncm/core/MANIFEST.lua; do not edit by hand')
    foreach ($f in $coreFiles) { $lines += ('shared_script "shared/core/{0}"' -f $f) }
    $lines += '-- ncm-core:end'
    $block = ($lines -join "`n")
    $newText = [regex]::Replace($text, '(?s)-- ncm-core:begin.*?-- ncm-core:end', { param($m) $block })
    if ($newText -ne $text) {
        $changes++
        Write-Host ("  [{0}] rewrite manifest block ({1} shared_script lines)" -f $res.Name, $coreFiles.Count)
        if (-not $Check) { [IO.File]::WriteAllText($manifestPath, $newText, (New-Object Text.UTF8Encoding($false))) }
    }
}

if ($changes -eq 0) { Write-Host 'ncm-build: up to date (no changes)' } else { Write-Host ("ncm-build: {0} change(s){1}" -f $changes, $(if ($Check) { ' would be made' } else { ' applied' })) }
if ($Check -and $changes -gt 0) { exit 1 }
exit 0
