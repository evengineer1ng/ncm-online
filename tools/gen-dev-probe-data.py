"""Generate the dev probe's data (L301, experiments E1-E5): harvested sockets for a few sites and a crowd pool.

Inputs:
  docs/research/open77/evidence/site_sockets.json   (tools/harvest-site-sockets.py)
  the OPEN//77 NPC record catalogue, https://open2077.net/data/npc-records-2.31.json (--records <path>)
Output: prototypes/ncm_dev_probe/server/probe_data.lua

The crowd pool is a FILTER over the platform's tagged catalogue, not a hand list (doc 45 §L): category crowd or
civilian, risk `candidate`, never a child record, never a vendor (their setup is special).

Usage:  python tools/gen-dev-probe-data.py --records <npc-records-2.31.json> [--sites id,id,...]
"""
import argparse, hashlib, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SOCKETS = os.path.join(ROOT, "docs", "research", "open77", "evidence", "site_sockets.json")
OUT = os.path.join(ROOT, "prototypes", "ncm_dev_probe", "server", "probe_data.lua")
DEFAULT_SITES = "corpo_plaza_-1103_-19,parque_del_mar_-2326_-1125,kabuki_bridge_-1106_1853"


def lua_str(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--records", required=True)
    ap.add_argument("--sites", default=DEFAULT_SITES)
    a = ap.parse_args()
    raw = open(a.records, "rb").read()
    cat = json.loads(raw)
    pool = sorted(r["record"] for r in cat["records"]
                  if r["risk"] == "candidate" and "child" not in r["category"]
                  and ("crowd" in r["category"] or "civilian" in r["category"])
                  and "vendor" not in r["category"] and "Vendor" not in r["record"])
    sockets = json.load(open(SOCKETS, encoding="utf-8"))
    want = a.sites.split(",")
    sites = {s["id"]: s for s in sockets["sites"] if s["id"] in want}
    missing = [w for w in want if w not in sites]
    if missing:
        raise SystemExit(f"unknown site ids: {missing}")
    lines = [
        "-- GENERATED by tools/gen-dev-probe-data.py -- do not edit by hand. Dev probe only (L301).",
        f"-- NPC catalogue sha256 {hashlib.sha256(raw).hexdigest()[:16]} ({cat.get('gameVersion')}), sockets radius {sockets['radius']} m.",
        "ProbeData = {}",
        "ProbeData.CROWD = {",
    ]
    lines += [f"  {lua_str(r)}," for r in pool]
    lines += ["}", "ProbeData.SITES = {"]
    for sid in want:
        s = sites[sid]
        lines.append(f"  [{lua_str(sid)}] = {{ name = {lua_str(s['name'])}, x = {s['x']}, y = {s['y']}, z = {s['z']}, sockets = {{")
        for k in s["spots"]:
            lines.append(f"    {{ x = {k['x']}, y = {k['y']}, z = {k['z']}, yaw = {k['yaw']}, kind = {lua_str(k['kind'])}, dist = {k['dist']} }},")
        lines.append("  } },")
    lines.append("}")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print(f"crowd pool {len(pool)} records; sites " + ", ".join(f"{sites[s]['name']}={sites[s]['count']}" for s in want) + f" -> {OUT}")


if __name__ == "__main__":
    main()
