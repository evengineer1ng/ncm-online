<#
.SYNOPSIS
  NCM Los Santos: a local FiveM (FXServer) dev server for GTA V Legacy (L319; doc 53). Dev only, this PC only.

.USAGE
  # once (or to refresh): FXServer artifacts (recommended build), Cfx.re's starter resources, server.cfg, our resources
  powershell -NoProfile -ExecutionPolicy Bypass -File .\tools\fivem-server.ps1 -Setup

  # the license key is a secret (keymaster.fivem.net), stored with DPAPI, never in a file:
  .\tools\ncm-secret.ps1 -Set fivem-license

  # start (detached, logs to tools\fivem\server-data\logs\fxserver-<stamp>.log) / stop
  powershell -NoProfile -ExecutionPolicy Bypass -File .\tools\fivem-server.ps1 -Start
  powershell -NoProfile -ExecutionPolicy Bypass -File .\tools\fivem-server.ps1 -Stop

  Then in the FiveM client: F8, `connect localhost:30120`.

  Everything under tools\fivem\ is downloaded or generated and is gitignored. Our resources are NOT copied: the
  server sees ncm\fivem\resources through a junction, so `restart ncm_ls_space` in the console picks up edits.
#>
[CmdletBinding()]
param([switch]$Setup, [switch]$Start, [switch]$Stop, [switch]$RunInner)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$base = Join-Path $root 'tools\fivem'
$artifacts = Join-Path $base 'artifacts'
$data = Join-Path $base 'server-data'
$logs = Join-Path $data 'logs'
$fx = Join-Path $artifacts 'FXServer.exe'

function Write-Cfg {
    $cfg = @'
# NCM Los Santos (dev) -- generated by tools/fivem-server.ps1; local dev only.
endpoint_add_tcp "0.0.0.0:30120"
endpoint_add_udp "0.0.0.0:30120"
sv_hostname "NCM Los Santos (dev)"
sets sv_projectName "NCM Los Santos"
sets sv_projectDesc "dev"
sv_maxclients 8
sv_master1 ""

# current cfx-server-data ships these; chat and sessionmanager are built into FXServer now. OneSync is set on the
# command line (it is an internal convar a cfg cannot change).
ensure mapmanager
ensure spawnmanager
ensure basic-gamemode
ensure baseevents

ensure ncm_ls_space
'@
    [IO.File]::WriteAllText((Join-Path $data 'server.cfg'), $cfg, (New-Object Text.UTF8Encoding($false)))
}

if ($Setup) {
    New-Item -ItemType Directory -Force $artifacts, $data, $logs, (Join-Path $data 'resources') | Out-Null
    $v = Invoke-RestMethod 'https://changelogs-live.fivem.net/api/changelog/versions/win32/server'
    $zip = Join-Path $base "server-$($v.recommended).zip"
    if (-not (Test-Path $zip)) {
        Write-Host "downloading FXServer recommended build $($v.recommended)" -ForegroundColor Cyan
        Invoke-WebRequest $v.recommended_download -OutFile $zip
    }
    if (-not (Test-Path (Join-Path $artifacts "BUILD-$($v.recommended)"))) {
        Get-ChildItem $artifacts -Force | Remove-Item -Recurse -Force
        Expand-Archive $zip -DestinationPath $artifacts -Force
        New-Item -ItemType File (Join-Path $artifacts "BUILD-$($v.recommended)") | Out-Null
    }
    $cfxDefault = Join-Path $data 'resources\[cfx-default]'
    if (-not (Test-Path -LiteralPath (Join-Path $data 'resources\[managers]'))) {
        Write-Host "downloading Cfx.re starter resources (cfx-server-data)" -ForegroundColor Cyan
        $czip = Join-Path $base 'cfx-server-data.zip'
        Invoke-WebRequest 'https://codeload.github.com/citizenfx/cfx-server-data/zip/refs/heads/master' -OutFile $czip
        $tmp = Join-Path $base 'cfx-tmp'
        if (Test-Path $tmp) { Remove-Item -Recurse -Force $tmp }
        Expand-Archive $czip -DestinationPath $tmp -Force
        # the starter folders are named `[cfx-default]` etc.: `[` is a PowerShell wildcard, so literal paths only
        Get-ChildItem -LiteralPath (Join-Path $tmp 'cfx-server-data-master\resources') -Directory | ForEach-Object {
            Move-Item -LiteralPath $_.FullName -Destination (Join-Path (Join-Path $data 'resources') $_.Name) -Force
        }
        Remove-Item -Recurse -Force $tmp
    }
    $link = Join-Path $data 'resources\[ncm]'
    if (-not (Test-Path -LiteralPath $link)) {
        New-Item -ItemType Junction -Path $link -Target (Join-Path $root 'ncm\fivem\resources') | Out-Null
    }
    Write-Cfg
    Write-Host "setup done: FXServer $($v.recommended), server-data at $data" -ForegroundColor Green
    return
}

if ($Stop) {
    Get-Process -Name FXServer -ErrorAction SilentlyContinue | ForEach-Object { "stopping FXServer pid $($_.Id)"; Stop-Process -Id $_.Id -Force }
    return
}

if ($RunInner) {
    # runs as the child of ncm-secret.ps1 -Run, with the license in this process's environment only
    if (-not $env:NCM_FIVEM_LICENSE) { throw 'no license in the environment (store it: .\tools\ncm-secret.ps1 -Set fivem-license)' }
    # rcon, localhost tooling only (tools/fivem-rcon.py): a random password kept in the gitignored toolsivem folder,
    # so `restart ncm_ls_space` never needs a full server restart (which would kick connected players)
    $pwFile = Join-Path $base 'rcon.pw'
    if (-not (Test-Path $pwFile)) {
        $bytes = New-Object byte[] 16; [Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
        [IO.File]::WriteAllText($pwFile, (($bytes | ForEach-Object { $_.ToString('x2') }) -join ''))
    }
    $rcon = (Get-Content $pwFile -Raw).Trim()
    Set-Location $data
    & $fx +set onesync on +exec server.cfg +set sv_licenseKey $env:NCM_FIVEM_LICENSE +set rcon_password $rcon
    return
}

if ($Start) {
    if (-not (Test-Path $fx)) { throw 'FXServer not set up: run with -Setup first' }
    if (Get-Process -Name FXServer -ErrorAction SilentlyContinue) { throw 'FXServer is already running (-Stop first)' }
    New-Item -ItemType Directory -Force $logs | Out-Null
    $stamp = Get-Date -Format 'yyyyMMdd-HHmmss'
    $out = Join-Path $logs "fxserver-$stamp.log"
    $err = Join-Path $logs "fxserver-$stamp.err.log"
    $secret = Join-Path $root 'tools\ncm-secret.ps1'
    $self = Join-Path $root 'tools\fivem-server.ps1'
    $cmd = "& '$secret' -Run -Env @{ 'NCM_FIVEM_LICENSE' = 'fivem-license' } -Argv @('powershell','-NoProfile','-ExecutionPolicy','Bypass','-File','$self','-RunInner')"
    $p = Start-Process -FilePath powershell -ArgumentList @('-NoProfile', '-ExecutionPolicy', 'Bypass', '-Command', $cmd) `
        -WorkingDirectory $root -WindowStyle Hidden -RedirectStandardOutput $out -RedirectStandardError $err -PassThru
    Write-Host "FXServer starting (launcher pid $($p.Id)); log $out" -ForegroundColor Green
    [Environment]::Exit(0)   # return now: the redirected child must not hold this console open
    return
}

Get-Help $MyInvocation.MyCommand.Path -Detailed
