#!/usr/bin/env python3
"""Generate NCM Pace's racer vehicle records (TweakXL) and its TweakDB dump list (L244, IDEA-788).

Every Paddock car record gets a racer clone, `Vehicle.ncm_racer_<record>`, identical to the vanilla record except
that the AI drives it with the engine's RACE profile (`Driving.Race_Driving`) instead of the traffic profile. Ambient
traffic keeps the vanilla records untouched. The Paddock server spawns the clone (ncm_paddock/server/live.lua
`recordFor`) and falls back to the vanilla record if the platform refuses it.

Also writes the list of TweakDB flats Pace reads back at startup (`NcmPace.reds` `DumpDriving`), so tuning works from
the game's real values: every `Driving.*` flat, and what the vanilla cars and drivers point at.

Usage:  python tools/gen-pace-racers.py
Inputs: ncm/core/data/vehicle_pool.lua (the Paddock's records) and, for the dump list, a TweakDB name table
        (tools/tweakdb-names.py reads CET's; pass --names <file> with one name per line).
"""
import argparse
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
POOL = os.path.join(ROOT, "ncm", "core", "data", "vehicle_pool.lua")
OUT_YAML = os.path.join(ROOT, "ncm", "pace", "r6", "tweaks", "ncm_pace", "racers.yaml")
OUT_REDS = os.path.join(ROOT, "ncm", "pace", "r6", "scripts", "ncm_pace", "NcmPaceDump.reds")
OUT_SCALES = os.path.join(ROOT, "ncm", "pace", "r6", "scripts", "ncm_pace", "NcmPaceScales.reds")

# NPC racer tune (owner, 2026-10-02: "they also need more pace"; "feel free to buff drivescale, brakescale, dragscale,
# gripscale ... npcs are special"). Applies ONLY to Vehicle.ncm_racer_* clones, which only the Paddock spawns.
#   race profile (TweakXL YAML): how hard the engine's racer believes it may accelerate, turn and brake, and how far it
#   looks ahead at speed -- vanilla 2.0 / 2.0 / 2.0 and 18 m from 30 m/s.
# 0.9.1 (owner, 2026-10-03, Westbrook Short Ring: an unmodified Hella finished ~50 s clear -- "that level and above should
# be able to match my current speed minimum"): the NPCs swung 16-28 m/s (median 22) round a constant-radius ring the
# Hella holds at ~27.5 -- the racer cornered on a cautious traction estimate, not on the car's grip. Corner speed goes
# with the square root of the lateral estimate: 3.5 -> 5.0 is about +20 %.
TRACTION = {"forwardAccelFactor": 3.8, "turningAccelFactor": 3.4, "brakingAccelFactor": 2.9}
# ...and the owner on the split (2026-10-03): point to point "if anything theyre a bitttt too fast ... a tad"; "oval theyre
# too slow". So the street racers ease back a touch below 0.9.0 (4.0 / 3.5 / 3.0), and OVALS get their own profile and
# their own clones (`Vehicle.ncm_racer_oval_<record>`), which the Paddock spawns only on an oval.
OVAL_TRACTION = {"forwardAccelFactor": 4.5, "turningAccelFactor": 5.0, "brakingAccelFactor": 3.5}
STEERING = {"maxTargetDistance": 26.0, "speedForMaxDistance": 45.0}
#   physics scales (NcmPaceScales.reds, a TweakXL ScriptableTweak): multiply each racer's OWN cloned engine and drive
#   model records, from the game's real values. Grip has no TweakDB number on these records (wheel friction is not in
#   the wheel setup), so it is not here; the traction estimate above is the cornering lever.
DRIVE_SCALE = 1.25     # vehEngineData.engineMaxTorque
BRAKE_SCALE = 1.30     # vehDriveModelData(AI).brakingFrictionFactor
DRAG_SCALE = 0.80      # vehDriveModelData(AI).airResistanceFactor
# L298 PERFORMANCE VARIANTS: an NPC's installed parts compose (parts.handling, the player formula) to a variant
# v0..v3 (economy.npc_garage.variant); `<racer>_v<n>` is the same clone with drive and brakes a further VARIANT_STEP
# each. Keep in step with economy.npc_garage VARIANTS / VARIANT_STEP.
VARIANTS = 4
VARIANT_STEP = 0.06
FALLBACK = "Vehicle.v_sport2_quadra_type66"     # ncm_paddock/server/live.lua recordFor's fallback
PROFILE = "Driving.Race_Driving"


def racer(record, oval=False):
    return ("Vehicle.ncm_racer_oval_" if oval else "Vehicle.ncm_racer_") + record.split(".", 1)[1]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--names", help="TweakDB name table, one per line (for the dump list)")
    a = ap.parse_args()
    records = sorted(set(re.findall(r"Vehicle\.[A-Za-z0-9_]+", open(POOL, encoding="utf-8").read())) | {FALLBACK})
    os.makedirs(os.path.dirname(OUT_YAML), exist_ok=True)
    with open(OUT_YAML, "w", encoding="utf-8", newline="\n") as f:
        traction = "".join(f"  {k}: {v}\n" for k, v in TRACTION.items())
        steering = "".join(f"  {k}: {v}\n" for k, v in STEERING.items())
        ovalTraction = "".join(f"  {k}: {v}\n" for k, v in OVAL_TRACTION.items())
        f.write(f"""# Generated by tools/gen-pace-racers.py; isolated NCM Pace RaceDrive tune (Paddock NPC racers only).
# Driving.Race_Driving refers to its parts by the fields steering / vision / traction. (0.8.5 set `inline1` / `inline2`,
# which TweakXL rejected as unknown properties -- KB-292 -- so only the vision override ever applied.)
Driving.NCM_Paddock_VisionParamsRace:
  $base: Driving.VisionParamsRace
  useSpeedLimit: false

Driving.NCM_Paddock_TractionRace:
  $base: Driving.VehicleAITractionEstimationRace
{traction}
Driving.NCM_Paddock_SteeringRace:
  $base: Driving.SteeringParamsForwardRace
{steering}
Driving.NCM_Paddock_Race_Driving:
  $base: Driving.Race_Driving
  vision: Driving.NCM_Paddock_VisionParamsRace
  traction: Driving.NCM_Paddock_TractionRace
  steering: Driving.NCM_Paddock_SteeringRace

Driving.NCM_Paddock_TractionRaceOval:
  $base: Driving.VehicleAITractionEstimationRace
{ovalTraction}
Driving.NCM_Paddock_Race_Driving_Oval:
  $base: Driving.Race_Driving
  vision: Driving.NCM_Paddock_VisionParamsRace
  traction: Driving.NCM_Paddock_TractionRaceOval
  steering: Driving.NCM_Paddock_SteeringRace
""")
        for oval, prof in ((False, "Driving.NCM_Paddock_Race_Driving"), (True, "Driving.NCM_Paddock_Race_Driving_Oval")):
            for record in records:
                f.write(f"{racer(record, oval)}:\n  $base: {record}\n  drivingParamsRace: {prof}\n\n")
                for v in range(1, VARIANTS):
                    f.write(f"{racer(record, oval)}_v{v}:\n  $base: {record}\n  drivingParamsRace: {prof}\n\n")
    print(f"{len(records)} NCM racer clones x {VARIANTS} variants x street/oval -> {os.path.relpath(OUT_YAML, ROOT)}")
    names, steps = [], []
    for oval in (False, True):
        for r in records:
            names.append(racer(r, oval)); steps.append(0)
            for v in range(1, VARIANTS):
                names.append(f"{racer(r, oval)}_v{v}"); steps.append(v)
    racers = ",\n      ".join('"' + n + '"' for n in names)
    stepList = ", ".join(str(x) for x in steps)
    with open(OUT_SCALES, "w", encoding="utf-8", newline="\n") as f:
        f.write(f"""// GENERATED by tools/gen-pace-racers.py -- do not edit by hand.
// NCM Pace NPC physics scales (owner, 2026-10-02: "npcs are special"). When TweakDB is built (a TweakXL
// ScriptableTweak, before any car spawns), each Paddock racer clone gets its OWN copies of its engine and drive-model
// records with the game's real values multiplied: drive x{DRIVE_SCALE}, brakes x{BRAKE_SCALE}, drag x{DRAG_SCALE}. Vanilla
// records and every car a player drives are untouched. A clone whose base car is not in this game is skipped.

public func NcmPace_RacerRecords() -> array<String> {{
  return [
      {racers}
  ];
}}

// L298: each racer's performance variant (0 = the base racer); drive and brakes x(1 + {VARIANT_STEP} x step) on top.
public func NcmPace_RacerSteps() -> array<Int32> {{
  return [{stepList}];
}}

// Clone the record `racer.field` points at, scale the named float flats, and point the racer at the clone.
public func NcmPace_CloneScaled(racer: String, field: String, tag: String, flats: array<String>, scales: array<Float>) -> Bool {{
  let src: TweakDBID = FromVariant<TweakDBID>(TweakDBInterface.GetFlat(TDBID.Create(racer + "." + field)));
  if !IsDefined(TweakDBInterface.GetRecord(src)) {{ return false; }}
  let name: String = racer + "__" + tag;
  if !TweakDBManager.CloneRecord(StringToName(name), src) {{ return false; }}
  let dst: TweakDBID = TDBID.Create(name);
  let i: Int32 = 0;
  while i < ArraySize(flats) {{
    let fid: TweakDBID = TDBID.Create(name + "." + flats[i]);
    let v: Float = FromVariant<Float>(TweakDBInterface.GetFlat(fid));
    if v != 0.0 {{ TweakDBManager.SetFlat(fid, ToVariant(v * scales[i])); }}
    i += 1;
  }}
  TweakDBManager.UpdateRecord(dst);
  return TweakDBManager.SetFlat(TDBID.Create(racer + "." + field), ToVariant(dst));
}}

public class NcmPaceRacerScales extends ScriptableTweak {{
  protected cb func OnApply() -> Void {{
    let done: Int32 = 0;
    let skipped: Int32 = 0;
    let names: array<String> = NcmPace_RacerRecords();
    let steps: array<Int32> = NcmPace_RacerSteps();
    let i: Int32 = 0;
    while i < ArraySize(names) {{
      let racer: String = names[i];
      let k: Float = 1.0 + {VARIANT_STEP} * Cast<Float>(steps[i]);
      let rid: TweakDBID = TDBID.Create(racer);
      if IsDefined(TweakDBInterface.GetRecord(rid)) {{
        NcmPace_CloneScaled(racer, "vehEngineData", "engine", ["engineMaxTorque"], [{DRIVE_SCALE} * k]);
        NcmPace_CloneScaled(racer, "vehDriveModelData", "drive", ["brakingFrictionFactor", "airResistanceFactor"], [{BRAKE_SCALE} * k, {DRAG_SCALE}]);
        NcmPace_CloneScaled(racer, "vehDriveModelDataAI", "driveai", ["brakingFrictionFactor", "airResistanceFactor"], [{BRAKE_SCALE} * k, {DRAG_SCALE}]);
        TweakDBManager.UpdateRecord(rid);
        done += 1;
      }} else {{
        skipped += 1;
      }}
      i += 1;
    }}
    NcmPace_Log("racer scales: " + IntToString(done) + " racer(s) scaled (drive x{DRIVE_SCALE} brake x{BRAKE_SCALE} drag x{DRAG_SCALE}), " + IntToString(skipped) + " skipped (no base car)");
  }}
}}
""")
    print(f"racer physics scales -> {os.path.relpath(OUT_SCALES, ROOT)}")
    if a.names:
        names = [n.strip() for n in open(a.names, encoding="utf-8") if n.strip()]
        want = [n for n in names if re.match(r"^Driving\.[A-Za-z0-9_]+\.[A-Za-z0-9_]+$", n)]
        for r in (FALLBACK, "Vehicle.v_sport1_quadra_turbo"):
            for fld in ("driving", "drivingParamsGeneric", "drivingParamsRace", "drivingParamsPanic", "vehDriveModelDataAI"):
                want.append(f"{r}.{fld}")
        for fld in ("driving", "drivingParamsGeneric", "drivingParamsRace"):
            want.append(f"Character.WorkerMale.{fld}")
        body = ",\n      ".join('"' + n + '"' for n in want)
        with open(OUT_REDS, "w", encoding="utf-8", newline="\n") as f:
            f.write(f"""// GENERATED by tools/gen-pace-racers.py -- do not edit by hand.
// NCM Pace (L244, IDEA-788): the engine's driving profiles, read back from the game's own TweakDB at startup, so
// racer tuning works from real values. Read-only; logs through NcmPace_Log once per game start.

public func NcmPace_DrivingNames() -> array<String> {{
  return [
      {body}
  ];
}}

public func NcmPace_DumpDriving() -> Void {{
  let names: array<String> = NcmPace_DrivingNames();
  let shown: Int32 = 0;
  for name in names {{
    // No GetFlat in scripts without Codeware: every flat is read every way. The field's real type is the one whose
    // value makes sense (a record reference shows as a record name; floats, bools and ints as numbers).
    let id: TweakDBID = TDBID.Create(name);
    let fk: TweakDBID = TweakDBInterface.GetForeignKeyDefault(id);
    let text: String = "f=" + FloatToString(TweakDBInterface.GetFloat(id, -9999.0)) + " b=" + ToString(TweakDBInterface.GetBool(id, false))
      + " i=" + IntToString(TweakDBInterface.GetInt(id, -9999)) + " fk=" + TDBID.ToStringDEBUG(fk);
    NcmPace_Log("tdb: " + name + " = " + text);
    shown += 1;
  }}
  NcmPace_Log("tdb: " + IntToString(shown) + " of " + IntToString(ArraySize(names)) + " driving flats read");
}}
""")
        print(f"{len(want)} dump names -> {os.path.relpath(OUT_REDS, ROOT)}")


if __name__ == "__main__":
    main()
