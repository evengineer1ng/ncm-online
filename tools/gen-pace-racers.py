#!/usr/bin/env python3
"""Generate NCM Pace's racer vehicle records (TweakXL) and its TweakDB dump list (L244, IDEA-788).

Every Paddock car record gets a racer clone, `Vehicle.ncm_racer_<record>`, identical to the vanilla record except
that the AI drives it with the engine's RACE profile (`Driving.Race_Driving`) instead of the traffic profile. Ambient
traffic keeps the vanilla records untouched. The Paddock server spawns the clone (ncm_paddock/server/live.lua
`recordFor`) and falls back to the vanilla record if the platform refuses it.

Also writes the list of TweakDB flats Pace reads back at startup (`NcmPace.reds` `DumpDriving`), so tuning works from
the game's real values: every `Driving.*` flat, and what the vanilla cars and drivers point at.

Usage:  python tools/gen-pace-racers.py
Inputs: ncm/core/data/vehicle_pool.lua (the Paddock's records) and, for the dump list, a TweakDB name table
        (tools/tweakdb-names.py reads CET's; pass --names <file> with one name per line).
"""
import argparse
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
POOL = os.path.join(ROOT, "ncm", "core", "data", "vehicle_pool.lua")
OUT_YAML = os.path.join(ROOT, "ncm", "pace", "r6", "tweaks", "ncm_pace", "racers.yaml")
OUT_REDS = os.path.join(ROOT, "ncm", "pace", "r6", "scripts", "ncm_pace", "NcmPaceDump.reds")
FALLBACK = "Vehicle.v_sport2_quadra_type66"     # ncm_paddock/server/live.lua recordFor's fallback
PROFILE = "Driving.Race_Driving"


def racer(record):
    return "Vehicle.ncm_racer_" + record.split(".", 1)[1]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--names", help="TweakDB name table, one per line (for the dump list)")
    a = ap.parse_args()
    records = sorted(set(re.findall(r"Vehicle\.[A-Za-z0-9_]+", open(POOL, encoding="utf-8").read())) | {FALLBACK})
    os.makedirs(os.path.dirname(OUT_YAML), exist_ok=True)
    with open(OUT_YAML, "w", encoding="utf-8", newline="\n") as f:
        f.write("""# Generated by tools/gen-pace-racers.py; isolated NCM Pace RaceDrive tune.
# Keep one coherent AIVehicleRacingCommand on the authored continuous oval spline.
Driving.NCM_Paddock_Race_Driving_inline1:
  $base: Driving.Race_Driving_inline1
  useSpeedLimit: false

Driving.NCM_Paddock_Race_Driving_inline2:
  $base: Driving.Race_Driving_inline2
  forwardAccelFactor: 3.0
  turningAccelFactor: 3.0

Driving.NCM_Paddock_VisionParamsRace:
  $base: Driving.VisionParamsRace
  useSpeedLimit: false

Driving.NCM_Paddock_Race_Driving:
  $base: Driving.Race_Driving
  inline1: Driving.NCM_Paddock_Race_Driving_inline1
  inline2: Driving.NCM_Paddock_Race_Driving_inline2
  vision: Driving.NCM_Paddock_VisionParamsRace

""")
        for record in records:
            f.write(f"{racer(record)}:\n  $base: {record}\n  drivingParamsRace: Driving.NCM_Paddock_Race_Driving\n\n")
    print(f"{len(records)} NCM racer clones -> {os.path.relpath(OUT_YAML, ROOT)}")
    if a.names:
        names = [n.strip() for n in open(a.names, encoding="utf-8") if n.strip()]
        want = [n for n in names if re.match(r"^Driving\.[A-Za-z0-9_]+\.[A-Za-z0-9_]+$", n)]
        for r in (FALLBACK, "Vehicle.v_sport1_quadra_turbo"):
            for fld in ("driving", "drivingParamsGeneric", "drivingParamsRace", "drivingParamsPanic", "vehDriveModelDataAI"):
                want.append(f"{r}.{fld}")
        for fld in ("driving", "drivingParamsGeneric", "drivingParamsRace"):
            want.append(f"Character.WorkerMale.{fld}")
        body = ",\n      ".join('"' + n + '"' for n in want)
        with open(OUT_REDS, "w", encoding="utf-8", newline="\n") as f:
            f.write(f"""// GENERATED by tools/gen-pace-racers.py -- do not edit by hand.
// NCM Pace (L244, IDEA-788): the engine's driving profiles, read back from the game's own TweakDB at startup, so
// racer tuning works from real values. Read-only; logs through NcmPace_Log once per game start.

public func NcmPace_DrivingNames() -> array<String> {{
  return [
      {body}
  ];
}}

public func NcmPace_DumpDriving() -> Void {{
  let names: array<String> = NcmPace_DrivingNames();
  let shown: Int32 = 0;
  for name in names {{
    // No GetFlat in scripts without Codeware: every flat is read every way. The field's real type is the one whose
    // value makes sense (a record reference shows as a record name; floats, bools and ints as numbers).
    let id: TweakDBID = TDBID.Create(name);
    let fk: TweakDBID = TweakDBInterface.GetForeignKeyDefault(id);
    let text: String = "f=" + FloatToString(TweakDBInterface.GetFloat(id, -9999.0)) + " b=" + ToString(TweakDBInterface.GetBool(id, false))
      + " i=" + IntToString(TweakDBInterface.GetInt(id, -9999)) + " fk=" + TDBID.ToStringDEBUG(fk);
    NcmPace_Log("tdb: " + name + " = " + text);
    shown += 1;
  }}
  NcmPace_Log("tdb: " + IntToString(shown) + " of " + IntToString(ArraySize(names)) + " driving flats read");
}}
""")
        print(f"{len(want)} dump names -> {os.path.relpath(OUT_REDS, ROOT)}")


if __name__ == "__main__":
    main()
