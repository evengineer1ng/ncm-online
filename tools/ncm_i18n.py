#!/usr/bin/env python3
"""Extract and validate NCM localization catalogs (stdlib only)."""
from __future__ import annotations
import argparse, ast, json, re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / "ncm-localized" / "bin" / "x64" / "plugins" / "cyber_engine_tweaks" / "mods" / "MT_Ecosystem"
PROTECTED = {"Night City", "Dogtown", "Watson", "Westbrook", "Heywood", "Pacifica", "Santo Domingo", "City Center", "Badlands"}
PLAYER_FILES = {"ui.lua", "ui_racing.lua", "ui_routes.lua", "ui_tuning.lua", "ui_knockout.lua", "ui_knockout_circuits.lua", "ui_garage.lua", "ui_vehicle_pool.lua", "ui_championships.lua", "settings.lua", "racing.lua", "race_commands.lua", "contact_events.lua", "fan_engine.lua", "betting.lua", "management.lua", "phone_bridge.lua", "ink_hud.lua", "checkpoint.lua", "mappins.lua"}
STRING = re.compile(r'(["\'])(.*?)(?<!\\)\1')
VISIBLE_CALL = re.compile(r'(?:ImGui\.(?:Text(?:Wrapped|Disabled)?|Button|SmallButton|Checkbox|BeginTabItem|BeginCombo|Selectable|InputText|CollapsingHeader|RadioButton|MenuItem)|label\s*=|description\s*=|title\s*=|subtitle\s*=|message\s*=|text\s*=|(?:string\.format|i18n\.format|formatTemplate|response|notify|emitMessage)\s*\()')

def decode(raw: str) -> str | None:
    try: return ast.literal_eval(raw)
    except Exception: return None

def slug(value: str) -> str:
    value = re.sub(r"##.*$", "", value).lower()
    value = re.sub(r"[^a-z0-9]+", "_", value).strip("_")[:54]
    return value or "text"

def surface(name: str) -> str:
    if name.startswith("ui_") or name == "ui.lua": return "ui"
    if name == "settings.lua": return "settings"
    if name in {"race_commands.lua", "contact_events.lua", "fan_engine.lua", "phone_bridge.lua", "management.lua", "betting.lua"}: return "sms"
    return "hud"

def extract():
    entries, context, seen, by_value = {}, {}, defaultdict(int), {}
    sources = [p for p in (ROOT / "modules").glob("*.lua") if p.name in PLAYER_FILES]
    sources += list((ROOT / "data").glob("*.lua"))
    for path in sorted(sources):
        in_concat = False
        for line_no, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            if "print(" in line or "[NCM/" in line: continue
            is_data = path.parent.name == "data"
            starts_concat = bool(re.search(r"(?:table|i18n)\.concat\s*\(\s*\{", line))
            if starts_concat: in_concat = True
            visible_line = bool(VISIBLE_CALL.search(line) or in_concat or (is_data and re.search(r"\b(?:name|label|description|title|summary)\s*=", line)))
            if not visible_line: continue
            for match in STRING.finditer(line):
                value = decode(match.group(0))
                if not value or len(value.strip()) < 2 or not re.search(r"[A-Za-z]", value): continue
                if value.startswith(("modules/", "data/", "/", "ncm_")): continue
                visible = value.split("##", 1)[0]
                if not re.search(r"\s", visible) and visible.lower() not in {"racing","garage","routes","tuning","championships","knockout","start","cancel","close","save","delete","reset","enable","disable","yes","no","auto"}: continue
                if re.fullmatch(r"[%#%\.0-9a-zA-Z_:/\\-]+", visible) and "%" in visible: continue
                if visible in by_value:
                    old = by_value[visible]
                    context[old].setdefault("additional_sources", []).append(f"modules/{path.name}:{line_no}")
                    continue
                group = "gameplay" if is_data else surface(path.name)
                base = f"{group}.{path.stem.removeprefix('ui_')}.{slug(visible)}"
                seen[base] += 1
                key = base if seen[base] == 1 else f"{base}_{seen[base]}"
                entries[key] = visible
                by_value[visible] = key
                context[key] = {"source": f"{path.parent.name}/{path.name}:{line_no}", "surface": group, "placeholders": sorted(set(re.findall(r"{([A-Za-z0-9_]+)}", visible))), "protected_names": sorted(p for p in PROTECTED if p in visible)}
            if in_concat and re.search(r"}\s*,?\s*[\"']?\\?n?[\"']?\s*\)", line): in_concat = False
    return entries, context

def write_outputs():
    entries, context = extract(); loc = ROOT / "locales"; loc.mkdir(exist_ok=True)
    (loc / "en-us.json").write_text(json.dumps({"locale":"en-us", "strings":entries}, ensure_ascii=False, indent=2)+"\n", encoding="utf-8")
    (loc / "translator-template.json").write_text(json.dumps({"locale":"replace-me", "strings":{k:"" for k in entries}}, ensure_ascii=False, indent=2)+"\n", encoding="utf-8")
    (loc / "context.json").write_text(json.dumps(context, ensure_ascii=False, indent=2)+"\n", encoding="utf-8")
    reverse = {v:k for k,v in entries.items()}
    lines = ["-- Generated by tools/ncm_i18n.py; do not edit.", "return {"]
    for value,key in sorted(reverse.items()):
        q=lambda s: '"'+s.replace('\\','\\\\').replace('"','\\"').replace('\n','\\n')+'"'
        lines.append(f"    [{q(value)}] = {q(key)},")
    lines.append("}")
    (loc / "reverse_index.lua").write_text("\n".join(lines)+"\n", encoding="utf-8")
    # Rival names are protected/invariant, but ArchiveXL still needs an entry in
    # every installed locale to prevent a missing LocKey display.
    archive_root = ROOT.parents[5] / "archive" / "pc" / "mod"
    rival_root = archive_root / "mt_ecosystem_named_rivals" / "localization"
    rival_en = rival_root / "en-us" / "onscreens" / "mt_ecosystem_named_rivals.json"
    locales = sorted(p.stem for p in loc.glob("*.json") if p.name not in {"context.json", "translator-template.json", "coverage.json"})
    if rival_en.exists():
        rival_text = rival_en.read_text(encoding="utf-8")
        for locale in locales:
            target = rival_root / locale / "onscreens" / "mt_ecosystem_named_rivals.json"
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(rival_text, encoding="utf-8")
        xl = ["localization:", "  onscreens:"] + [f"    {x}: mt_ecosystem_named_rivals\\localization\\{x}\\onscreens\\mt_ecosystem_named_rivals.json" for x in locales]
        (archive_root / "mt_ecosystem_named_rivals.xl").write_text("\n".join(xl)+"\n", encoding="utf-8")
    print(f"extracted {len(entries)} English entries")

def placeholders(v):
    if isinstance(v, str):
        named = {"{" + x + "}" for x in re.findall(r"{([A-Za-z0-9_]+)}", v)}
        printf = set(re.findall(r"%(?:\d+\$)?[-+ #0]*(?:\d+|\*)?(?:\.\d+|\.\*)?[hlL]?[diuoxXfFeEgGaAcspq]", v))
        return named | printf
    if isinstance(v, dict): return set().union(*(placeholders(x) for x in v.values()))
    return set()

def validate(strict=False):
    def load(path):
        def unique(pairs):
            out={}
            for key,value in pairs:
                if key in out: raise ValueError(f"duplicate key: {key}")
                out[key]=value
            return out
        return json.loads(path.read_text(encoding="utf-8"), object_pairs_hook=unique)
    base = load(ROOT/"locales/en-us.json")["strings"]
    failed = False; coverage = {}
    for path in sorted((ROOT/"locales").glob("*.json")):
        if path.name in {"context.json", "translator-template.json", "coverage.json"}: continue
        try: data=load(path); strings=data["strings"]
        except Exception as e: print(f"ERROR {path.name}: malformed catalog: {e}"); failed=True; continue
        missing=set(base)-set(strings); extra=set(strings)-set(base)
        for key in sorted(set(base)&set(strings)):
            if placeholders(base[key]) != placeholders(strings[key]): print(f"ERROR {path.name}: placeholders differ: {key}"); failed=True
            if isinstance(strings[key],dict) and "other" not in strings[key]: print(f"ERROR {path.name}: plural lacks 'other': {key}"); failed=True
            if path.name != "en-us.json" and any(p in base[key] and p not in json.dumps(strings[key],ensure_ascii=False) for p in PROTECTED): print(f"ERROR {path.name}: protected name changed: {key}"); failed=True
        translated=sum(1 for k,v in strings.items() if k in base and v not in ("",base[k]))
        coverage[path.stem] = {"total":len(base), "present":len(base)-len(missing), "translated":translated, "missing":len(missing), "obsolete":len(extra)}
        print(f"{path.name}: {len(base)-len(missing)}/{len(base)} present, {translated} translated, {len(extra)} obsolete")
        if missing:
            print("  missing: "+", ".join(sorted(missing)[:10]))
            if strict: failed=True
        if extra: print("  obsolete: "+", ".join(sorted(extra)[:10])); failed=True
    (ROOT/"locales/coverage.json").write_text(json.dumps(coverage,indent=2)+"\n",encoding="utf-8")
    raise SystemExit(1 if failed else 0)

if __name__ == "__main__":
    ap=argparse.ArgumentParser(); ap.add_argument("command",choices=("extract","validate")); ap.add_argument("--strict",action="store_true"); args=ap.parse_args()
    write_outputs() if args.command=="extract" else validate(args.strict)
