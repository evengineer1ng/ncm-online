#!/usr/bin/env python3
"""The road line of every race leg, for the Paddock server (IDEA-787, L247).

Since L243 the server knows a street route only by its authored points, so the race model's line was a chord through
buildings and the physical bubble could not set a street car down on a road. NCM Pace's bake already routes every
ordered pair of race nodes over the game's own lane graph (`ncm_pace_bake_legs`); this turns those lines into a
server-only Lua script for `ncm_paddock`, so `PaddockLive.pathFor` builds every street route from its legs' roads.

Each line is cut at its finish node (the bake's 80 m run-out is for the racer, not the model), thinned to a point every
<= 25 m and at every turn of >= 10 degrees, rounded to 0.1 m, and stored as one string per leg ("x,y,z;x,y,z;...").

Usage:  ncm/pace/build/Release/ncm_pace_bake_legs.exe ncm/pace/build/road-data ncm/core/data/nodes.lua > legs.jsonl
        python tools/gen-road-lines.py --legs legs.jsonl
"""
import argparse
import json
import math
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "ncm", "online", "resources", "ncm_paddock", "server", "roadlines_data.lua")
SPACING_M, TURN_DEG = 25.0, 10.0


def cut_runout(points, length):
    out, acc = [points[0]], 0.0
    for a, b in zip(points, points[1:]):
        d = math.hypot(b[0] - a[0], b[1] - a[1])
        if acc + d > length + 0.5:
            break
        acc += d
        out.append(b)
    return out


def thin(points):
    out = [points[0]]
    for i in range(1, len(points) - 1):
        p, last, nxt = points[i], out[-1], points[i + 1]
        d = math.hypot(p[0] - last[0], p[1] - last[1])
        h1 = math.atan2(p[1] - last[1], p[0] - last[0])
        h2 = math.atan2(nxt[1] - p[1], nxt[0] - p[0])
        turn = abs((math.degrees(h2 - h1) + 180) % 360 - 180)
        if d >= SPACING_M or (turn >= TURN_DEG and d >= 4.0):
            out.append(p)
    out.append(points[-1])
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--legs", required=True)
    a = ap.parse_args()
    legs = sorted((json.loads(l) for l in open(a.legs, encoding="utf-8") if l.strip()), key=lambda l: (l["from"], l["to"]))
    total = 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("-- GENERATED by tools/gen-road-lines.py from NCM Pace's leg bake -- do not edit by hand. (IDEA-787, L247)\n")
        f.write("-- The road line of every race leg (ordered pair of race nodes), routed over the game's lane graph.\n")
        f.write("-- Server only: never shipped to a client. Decoded on demand by PaddockLive.pathFor.\n")
        f.write("PaddockRoadLines = {\n")
        for leg in legs:
            pts = thin(cut_runout([tuple(p) for p in leg["points"]], leg["lengthM"]))
            total += len(pts)
            enc = ";".join(f"{x:.1f},{y:.1f},{z:.1f}" for x, y, z in pts)
            f.write(f'  ["{leg["from"]}__{leg["to"]}"] = "{enc}",\n')
        f.write("}\n")
    print(f"{len(legs)} legs, {total} points, {os.path.getsize(OUT) // 1024} KB -> {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
