#!/usr/bin/env python3
"""Port the extracted garage sites into ncm/core/paddock/garages_data.lua (doc 44 §11, IDEA-735, IDEA-736).

Source: `references/world-pois/garage_sites.json`, written by `tools/world-pois/build_registry.py` from the game's own
cooked map pins (docs/research/open77/NIGHT_CITY_POI_EXTRACTION.md). That folder is git-ignored because raw game data
is not redistributed. This tool carries DERIVED FACTS only -- a position, a kind and a district -- into NCM's own
registry, the way the fuel stations were carried (IDEA-704). No journal path, entity id or raw record crosses over.

Rules, all deliberate:
  * Autofixer sites are dropped. They are NCM's market terminals (L206), not workplaces a team rents.
  * District: a district word in the site's own quest paths wins; a Phantom Liberty (`ep1/`) site inside Dogtown's
    bounds is Dogtown; otherwise the nearest route node's region within 1,500 m; otherwise Badlands east/south of the
    city, else "Outskirts". Coarse by design: it labels a place for a player, it decides nothing.
  * Positions are rounded to 0.1 m and the list is sorted west-to-east, so ids are stable across re-extractions.
  * A pin is not a doorway (the research note): every site ships `checked = false`. The runtime lets the owner mark
    a site good or bad in play (`ncm.paddock.garage`), and a bad site leaves the rental pool.

The Lua file is GENERATED; `--check` fails when it no longer matches the source.

Usage:  python tools/paddock-garages-port.py [--check]
"""
import argparse
import json
import math
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
SRC = os.path.join(ROOT, "references", "world-pois", "garage_sites.json")
NODES = os.path.join(ROOT, "ncm", "core", "data", "nodes.lua")
OUT = os.path.join(ROOT, "ncm", "core", "paddock", "garages_data.lua")

KINDS = ("garage", "workshop", "parking")
DISTRICT_WORDS = [
    ("wesbrook", "Westbrook"), ("westbrook", "Westbrook"), ("japan_town", "Westbrook"), ("japantown", "Westbrook"),
    ("charter_hill", "Westbrook"), ("north_oak", "Westbrook"),
    ("santo_domingo", "Santo Domingo"), ("arroyo", "Santo Domingo"), ("rancho_coronado", "Santo Domingo"),
    ("heywood", "Heywood"), ("wellsprings", "Heywood"), ("vista_del_rey", "Heywood"), ("glen", "Heywood"),
    ("watson", "Watson"), ("kabuki", "Watson"), ("little_china", "Watson"), ("northside", "Watson"),
    ("city_center", "City Center"), ("downtown", "City Center"), ("corpo_plaza", "City Center"),
    ("pacifica", "Pacifica"), ("coastview", "Pacifica"), ("west_wind", "Pacifica"),
    ("badlands", "Badlands"), ("inland_avenue", "Badlands"),
]


def load_nodes():
    text = open(NODES, encoding="utf-8").read()
    out = []
    for m in re.finditer(r"x\s*=\s*(-?[\d.]+)\s*,\s*y\s*=\s*(-?[\d.]+).*?region\s*=\s*\"([^\"]+)\"", text):
        out.append((float(m.group(1)), float(m.group(2)), m.group(3)))
    if not out:
        sys.exit("no nodes with regions parsed from " + NODES)
    return out


def district_of(site, nodes):
    for ref in site.get("refs", []):
        low = ref.lower()
        for word, name in DISTRICT_WORDS:
            if "/" + word + "/" in "/" + low + "/" or ("_" + word) in low:
                return name
    # Phantom Liberty courier garages are spread across the whole city, so `ep1/` alone names nothing: only a site
    # inside Dogtown's own bounds is Dogtown.
    if any(r.startswith("ep1/") for r in site.get("refs", [])) and -2700 <= site["x"] <= -1100 and -3200 <= site["y"] <= -1800:
        return "Dogtown"
    best, best_d = None, 1e18
    for x, y, region in nodes:
        d = math.hypot(site["x"] - x, site["y"] - y)
        if d < best_d:
            best, best_d = region, d
    if best_d <= 1500:
        return best
    return "Badlands" if site["x"] > 1000 or site["y"] < -2500 else "Outskirts"


def build():
    if not os.path.exists(SRC):
        sys.exit("missing " + SRC + " -- run tools/world-pois/build_registry.py first (see the research note)")
    sites = json.load(open(SRC, encoding="utf-8"))
    nodes = load_nodes()
    rows = []
    for s in sites:
        if s.get("kind") not in KINDS:
            continue
        rows.append({
            "kind": s["kind"],
            "x": round(float(s["x"]), 1), "y": round(float(s["y"]), 1), "z": round(float(s["z"]), 1),
            "district": district_of(s, nodes),
        })
    rows.sort(key=lambda r: (r["x"], r["y"]))
    lines = [
        "-- ncm-core data: paddock.garages_data",
        "-- GENERATED by tools/paddock-garages-port.py from the game's own map pins (IDEA-736). Do not edit by hand.",
        "-- Derived facts only: position, kind, district. `checked` is false until an in-engine look says the site works.",
        "local Core = NcmCore",
        "",
        'Core.define("paddock.garages_data", function(C)',
        "    local M = { version = \"0.1.0\" }",
        "    M.SITES = {",
    ]
    for i, r in enumerate(rows, 1):
        lines.append('        { id = "g%03d", kind = "%s", district = "%s", x = %.1f, y = %.1f, z = %.1f },'
                     % (i, r["kind"], r["district"], r["x"], r["y"], r["z"]))
    lines += ["    }", "    return M", "end)", ""]
    return "\n".join(lines), rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text, rows = build()
    if args.check:
        have = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if have != text:
            sys.exit("garages_data.lua is stale: re-run tools/paddock-garages-port.py")
        print("garages_data.lua matches (%d sites)" % len(rows))
        return
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    by = {}
    for r in rows:
        by[r["district"]] = by.get(r["district"], 0) + 1
    print("wrote %d sites: %s" % (len(rows), ", ".join("%s %d" % kv for kv in sorted(by.items()))))


if __name__ == "__main__":
    main()
