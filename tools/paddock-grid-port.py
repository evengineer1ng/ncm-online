#!/usr/bin/env python3
"""Port NCM single-player's grid formation settings into ncm/core/data/grid_profiles.lua (L232).

The owner authored every route node in NCM single player and tuned how its AI grid lines up: the node heading, then
per-route `profileSettings` in data/default_roots_pack.lua, over the global defaults in modules/settings.lua. The
Online port had dropped those ("per-root profile settings stay in SP"), and the first Paddock street grids came out
rotated and off the road. This carries exactly the grid keys across, from the owner's own files, so nothing is
retyped:

    gridHeadingOffsetDeg  startSlotHeadingOffsetDeg  aiSlotHeadingOffsetDeg  gridLateralShiftM  aiGridRowSpacingM
    aiGridStartSetbackM  aiGridColOffsetM

and (L234) the keys SP's ai_vehicles.lua drives its race AI with: the capped launch release, the launch grace, the
recommand cadence, the stall thresholds, the race minimum-speed fraction, the target distance, the finish run-off and
the traffic clear radius.

SP's slot rotation is startSlotHeadingOffsetDeg when set (its default is -90), else aiSlotHeadingOffsetDeg
(ai_vehicles.lua resolveUnifiedSlotHeadingOffsetDeg).

The Lua file is GENERATED; `--check` fails when it no longer matches the SP sources.

Usage:  python tools/paddock-grid-port.py [--check]
"""
import argparse
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
SP = os.path.join(ROOT, "ncm-localized", "bin", "x64", "plugins", "cyber_engine_tweaks", "mods", "MT_Ecosystem")
PACK = os.path.join(SP, "data", "default_roots_pack.lua")
SETTINGS = os.path.join(SP, "modules", "settings.lua")
OUT = os.path.join(ROOT, "ncm", "core", "data", "grid_profiles.lua")
KEYS = ["gridHeadingOffsetDeg", "startSlotHeadingOffsetDeg", "aiSlotHeadingOffsetDeg", "gridLateralShiftM", "aiGridRowSpacingM", "aiGridStartSetbackM", "aiGridColOffsetM",
        # the launch and race-driving keys (L234): how SP gets its AI off the line and keeps it racing
        "aiLaunchGraceTimeS", "aiLaunchReleaseMaxSpeedCapMps", "aiLaunchReleaseMinSpeedCapMps", "aiLaunchReleaseForcedSpeedCapMps",
        "aiLaunchReleaseTargetDistanceM", "aiAutonomousTargetDistanceM", "aiRecommandIntervalS", "aiStallSpeedThreshMps",
        "aiStallTimeThreshS", "aiMinSpeedFrac", "aiFinishRunoffDistanceM", "trafficClearRadiusM"]


def defaults():
    text = open(SETTINGS, encoding="utf-8").read()
    out = {}
    for k in KEYS:
        m = re.search(r'key = "%s".*?default = (-?[\d.]+)' % k, text)
        if not m:
            sys.exit("no default for %s in %s" % (k, SETTINGS))
        out[k] = float(m.group(1))
    return out


def profiles():
    script = ('local p = dofile([[%s]]) for _, r in ipairs(p.roots) do local s = r.profileSettings or {} '
              'local parts = { r.rootId } for _, k in ipairs({%s}) do parts[#parts + 1] = tostring(s[k]) end '
              'print(table.concat(parts, "\\t")) end') % (PACK, ", ".join('"%s"' % k for k in KEYS))
    res = subprocess.run(["lua", "-e", script], capture_output=True, text=True, check=True)
    out = {}
    for line in res.stdout.splitlines():
        parts = line.split("\t")
        vals = {k: float(v) for k, v in zip(KEYS, parts[1:]) if v != "nil"}
        if vals:
            out[parts[0]] = vals
    return out


def fmt(v):
    s = repr(float(v))
    return s[:-2] if s.endswith(".0") else s


def build():
    d, p = defaults(), profiles()
    lines = [
        "-- ncm-core data: data.grid_profiles",
        "-- GENERATED by tools/paddock-grid-port.py from NCM single player (data/default_roots_pack.lua profileSettings over",
        "-- modules/settings.lua defaults). The owner's own grid tuning; do not edit by hand -- tune it in SP and re-run.",
        "local Core = NcmCore",
        "",
        'Core.define("data.grid_profiles", function(C)',
        '    local M = { version = "0.1.0" }',
        "    M.DEFAULTS = { " + ", ".join("%s = %s" % (k, fmt(d[k])) for k in KEYS) + " }",
        "    M.ROOTS = {",
    ]
    for root in sorted(p):
        lines.append('        ["%s"] = { %s },' % (root, ", ".join("%s = %s" % (k, fmt(v)) for k, v in sorted(p[root].items()))))
    lines += [
        "    }",
        "    --- The grid settings for a route: its own profile over the defaults.",
        "    function M.forRoot(rootId)",
        "        local out = {}",
        "        for k, v in pairs(M.DEFAULTS) do out[k] = v end",
        "        for k, v in pairs(M.ROOTS[rootId or \"\"] or {}) do out[k] = v end",
        "        return out",
        "    end",
        "    return M",
        "end)",
        "",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    text = build()
    if ap.parse_args().check:
        have = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if have != text:
            sys.exit("grid_profiles.lua is stale: re-run tools/paddock-grid-port.py")
        print("grid_profiles.lua matches the SP sources")
        return
    open(OUT, "w", encoding="utf-8", newline="\n").write(text)
    print("wrote " + OUT)


if __name__ == "__main__":
    main()
