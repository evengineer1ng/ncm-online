-- tools/gen-gearbox-records.lua -- the manual clones, generated from core `machine.gearbox` (L306).
--
--   lua tools/gen-gearbox-records.lua [repo-root] [--check]
--
-- Writes, from `machine.gearbox.FACTORY` x `SPECS` x each model's runtime records:
--   ncm/gearbox/r6/tweaks/ncm_gearbox/clones.yaml   TweakXL: one vehicle clone per (record, manual spec), `$base`d on
--                                                   the model record -- same car, same everything, until the DLL
--                                                   points it at its own engine data
--   ncm/gearbox/data/ncm_gearbox_specs.json         the DLL's input: each clone's forward-gear ratios (fractions of
--                                                   the car's automatic reach: min(catalogue top, native top x
--                                                   gearHeadroom)), shift time and catalogue top
-- `--check` regenerates in memory and fails if either file differs (the gate runs it: YAML <-> core parity).
local root = (arg[1] and not arg[1]:match("^%-%-")) and arg[1] or "."
local check = false
for _, a in ipairs(arg) do if a == "--check" then check = true end end

local core = root .. "/ncm/core/"
dofile(core .. "init.lua")
for _, f in ipairs(dofile(core .. "MANIFEST.lua")) do dofile(core .. f) end
local Gearbox = NcmCore.get("machine.gearbox")
local Catalogue = NcmCore.get("data.vehicle_catalogue")
local Parts = NcmCore.get("parts.handling")

local keys = {}
for key in pairs(Gearbox.FACTORY) do keys[#keys + 1] = key end
table.sort(keys)

local yaml = {
    "# Generated by tools/gen-gearbox-records.lua from ncm/core/machine/gearbox.lua -- do not edit by hand (L306).",
    "# One clone per (model record, manual spec). The NCM Gearbox DLL gives each its own engine data and gears at load.",
    "",
}
local clones = {}
for _, key in ipairs(keys) do
    local entry = Catalogue.byKey(key)
    if not entry then error("machine.gearbox.FACTORY names an unknown vehicleKey: " .. key) end
    local records = {}
    for _, r in ipairs(entry.runtimeRecords) do records[#records + 1] = r end
    table.sort(records)
    for _, specId in ipairs(Gearbox.cloneSpecs(key, entry.category)) do
        local spec = Gearbox.spec(specId)
        for _, base in ipairs(records) do
            local clone = Gearbox.record(base, { kind = spec.kind, spec = spec.id })
            yaml[#yaml + 1] = clone .. ":"
            yaml[#yaml + 1] = "  $base: " .. base
            yaml[#yaml + 1] = ""
            local ratios = {}
            for i, r in ipairs(Gearbox.ratios(spec)) do ratios[i] = ("%.6f"):format(r) end
            -- the reference the ratios are fractions of (the DLL takes the LOWER of the two): the catalogue's authored
            -- top speed, and the model's native top gear x `gearHeadroom` -- how far Carrier stretches an automatic's
            -- chain (L162). Together: what the same car reaches as an automatic on NCM. 0 = none authored.
            local topKph = Catalogue.topSpeedKph(base) or 0
            clones[#clones + 1] = ('    { "record": "%s", "base": "%s", "spec": "%s", "shiftMs": %d, "topKph": %d, "ratios": [%s] }')
                :format(clone, base, spec.id, spec.shiftMs, topKph, table.concat(ratios, ", "))
        end
    end
end

local outputs = {
    [root .. "/ncm/gearbox/r6/tweaks/ncm_gearbox/clones.yaml"] = table.concat(yaml, "\n"),
    [root .. "/ncm/gearbox/data/ncm_gearbox_specs.json"] = table.concat({
        "{",
        '  "generatedBy": "tools/gen-gearbox-records.lua",',
        '  "reverseFirst": true,',
        ('  "gearHeadroom": %.2f,'):format(Parts.GEAR_HEADROOM),
        '  "clones": [',
        table.concat(clones, ",\n"),
        "  ]",
        "}",
        "",
    }, "\n"),
}

local bad = 0
for path, text in pairs(outputs) do
    if check then
        local f = io.open(path, "rb")
        local have = f and f:read("*a") or nil
        if f then f:close() end
        if have ~= text then
            bad = bad + 1
            print("  FAIL " .. path .. " is stale: run lua tools/gen-gearbox-records.lua")
        end
    else
        local f = assert(io.open(path, "wb"))
        f:write(text)
        f:close()
        print("wrote " .. path)
    end
end
print(("gearbox records: %d clone(s)%s"):format(#clones, check and (", " .. bad .. " stale") or ""))
if bad > 0 then os.exit(1) end
