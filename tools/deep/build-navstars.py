"""Generate client data from the server star catalogue (Hipparcos, doc 57): 
  space.data.navstars  -- the stars a drive can be pointed at on a host without the full catalogue (nearest + named)
  web/deep/skystars.js -- the overlay's star field: every star brighter than Hp 6.5 plus every star within 25 pc, with
                          positions (pc, ICRS) and absolute magnitude, so the sky can be drawn from ANY position.
Usage: python build-navstars.py <core/space dir with stars/> <out navstars.lua> <out skystars.js>
"""
import math, os, sys, json
import lupa.lua54 as L
core, out_lua, out_js = sys.argv[1], sys.argv[2], sys.argv[3]
lua = L.LuaRuntime(unpack_returned_tuples=True)
live = os.path.join(os.path.expanduser('~'), 'deepwork', 'live-20261012', 'ncm_world', 'shared', 'core', 'init.lua')
lua.execute(open(live, encoding='utf-8').read())
sd = os.path.join(core, 'stars')
for f in sorted(os.listdir(sd)):
    lua.execute(open(os.path.join(sd, f), encoding='utf-8').read())
S = lua.eval('NcmCore.get("space.data.stars")')
named = {}
for hip, rec in (S.named or {}).items():
    named[int(hip)] = rec.name
rows = []
for c in range(1, int(S.chunks) + 1):
    ch = lua.eval('NcmCore.get("space.data.stars.%d")' % c)
    n = len(ch.hip)
    for k in range(1, n + 1):
        x, y, z = ch.x[k], ch.y[k], ch.z[k]
        d = math.sqrt(x*x + y*y + z*z)
        hp, bv, mass = ch.hp[k], ch.bv[k], ch.mass[k]
        absmag = hp - 5 * (math.log10(max(d, 1e-6)) - 1)
        rows.append((int(ch.hip[k]), x, y, z, d, hp, bv, mass, absmag))
print("stars", len(rows))
nav = [r for r in rows if r[4] <= 6.2 or r[0] in named]
nav.sort(key=lambda r: r[4])
with open(out_lua, 'w', encoding='utf-8') as f:
    f.write('-- ncm-core module: space.data.navstars -- GENERATED by drives/tools/build-navstars.py; do not edit.\n')
    f.write('-- Doc 58: the stars a drive can be pointed at on a host that does not load the full catalogue (the client):\n')
    f.write('-- every Hipparcos star within 6.2 pc plus the named ones. Same rows as space.data.stars (pc, ICRS, mass Msun).\n')
    f.write('local Core = NcmCore\nCore.define("space.data.navstars", function()\n    return {\n')
    for r in nav:
        nm = named.get(r[0], "HIP %d" % r[0]).replace('"', "'")
        f.write('        { hip = %d, name = "%s", x = %.6f, y = %.6f, z = %.6f, mass = %.4f },\n' % (r[0], nm, r[1], r[2], r[3], r[7]))
    f.write('    }\nend)\n')
print("nav", len(nav))
sky = [r for r in rows if r[5] <= 6.5 or r[4] <= 25.0]
flat = []
for r in sky:
    flat += [round(r[1], 5), round(r[2], 5), round(r[3], 5), round(r[8], 2), round(r[6] if r[6] == r[6] else 0.6, 2)]
with open(out_js, 'w', encoding='utf-8') as f:
    f.write('// GENERATED by drives/tools/build-navstars.py from the Hipparcos new reduction (van Leeuwen 2007, CDS I/311).\n')
    f.write('// Doc 58: the drive overlay\'s stars: x, y, z (pc, ICRS, from the Sun), absolute Hp magnitude, B-V; 5 per star.\n')
    f.write('window.NCM_SKYSTARS = %s;\n' % json.dumps(flat, separators=(',', ':')))
    f.write('window.NCM_SKYSTARS_NAMED = %s;\n' % json.dumps({str(k): v for k, v in named.items()}, separators=(',', ':')))
print("sky", len(sky))
