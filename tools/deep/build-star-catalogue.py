#!/usr/bin/env python3
"""Build NCM Deep's star catalogue (core module `space.data.stars`) from the Hipparcos new reduction (doc 57 §1).

Source: van Leeuwen F. (2007), "Hipparcos, the New Reduction of the Raw Data", A&A 474, 653; CDS catalogue I/311
(cdsarc.cds.unistra.fr/ftp/I/311/hip2.dat.gz). ESA/CDS data, free to use with this acknowledgement. NOT the AMNH
Digital Universe speck files OpenSpace ships (those are under AMNH's own terms).

Kept: stars with a positive parallax measured to >= MIN_SNR sigma (a real distance), plus every star brighter than
Hp 6.5 with any positive parallax (the naked-eye sky). Positions: ICRS unit vector at epoch 1991.25 times 1/parallax,
in parsecs (static: proper motion is not applied yet). Mass: ESTIMATED from absolute Hp magnitude with the
main-sequence mass-luminosity relation (L ~ M^3.5), clamped to [0.08, 60] Msun -- wrong for giants and white dwarfs,
labelled `estimated`; the handful of stars below carry published masses instead.

Usage: python tools/build-star-catalogue.py data/hipparcos/hip2.dat.gz core/space/stars
"""
import gzip
import math
import os
import sys

CHUNK = 2000
BRIGHT_SKY = 6.0
MIN_SNR = 5.0
BRIGHT_HP = 6.5
# Published masses and names for stars a player will ask about (HIP -> (name, mass Msun, source)).
KNOWN = {
    70890: ("Proxima Centauri", 0.1221, "Mann et al. 2015"),
    71683: ("Alpha Centauri A", 1.0788, "Akeson et al. 2021"),
    71681: ("Alpha Centauri B", 0.9092, "Akeson et al. 2021"),
    87937: ("Barnard's Star", 0.144, "Ribas et al. 2018"),
    32349: ("Sirius", 2.063, "Bond et al. 2017 (A only)"),
    37279: ("Procyon", 1.478, "Liebert et al. 2013 (A only)"),
    91262: ("Vega", 2.135, "Monnier et al. 2012"),
    27989: ("Betelgeuse", 16.5, "Dolan et al. 2016"),
    11767: ("Polaris", 5.13, "Evans et al. 2018"),
    24436: ("Rigel", 21.0, "Przybilla et al. 2006"),
    69673: ("Arcturus", 1.08, "Ramirez & Allende Prieto 2011"),
    24608: ("Capella", 2.57, "Torres et al. 2015 (Aa)"),
    16537: ("Epsilon Eridani", 0.82, "Gonzalez et al. 2010"),
    8102: ("Tau Ceti", 0.783, "Teixeira et al. 2009"),
    54035: ("Lalande 21185", 0.39, "estimated (M dwarf)"),
    104214: ("61 Cygni A", 0.70, "Kervella et al. 2008"),
    104217: ("61 Cygni B", 0.63, "Kervella et al. 2008"),
    80763: ("Antares", 12.0, "Ohnaka et al. 2013"),
    65474: ("Spica", 11.43, "Tkachenko et al. 2016 (A)"),
    97649: ("Altair", 1.86, "Bouchaud et al. 2020"),
}


# Published parallaxes (mas) that replace Hipparcos's where its per-component values pull a system apart: Hipparcos
# gives Alpha Cen A and B parallaxes ~40 mas apart, which would put B 0.23 ly from A (they are ~20 AU apart).
PLX_OVERRIDE = {
    71683: (747.17, "Kervella et al. 2016 (A/B system)"),
    71681: (747.17, "Kervella et al. 2016 (A/B system)"),
    70890: (768.07, "Gaia DR3 (Proxima)"),
}


def mass_estimate(abs_mag):
    lum = 10 ** ((4.83 - abs_mag) / 2.5)
    return max(0.08, min(60.0, lum ** (1 / 3.5)))


def main(src, out):
    rows = []
    for line in gzip.open(src, "rt"):
        hip = int(line[0:6])
        ra, de = float(line[15:28]), float(line[29:42])
        plx, eplx = float(line[43:50]), float(line[83:89])
        hp = float(line[129:136])
        bv_s = line[152:158].strip()
        bv = float(bv_s) if bv_s else 0.65
        if hip in PLX_OVERRIDE:
            plx, eplx = PLX_OVERRIDE[hip][0], 0.1
        if plx <= 0:
            continue
        if plx / max(eplx, 1e-6) < MIN_SNR and not (hp < BRIGHT_HP):
            continue
        d = 1000.0 / plx  # parsecs
        x, y, z = d * math.cos(de) * math.cos(ra), d * math.cos(de) * math.sin(ra), d * math.sin(de)
        absm = hp + 5 + 5 * math.log10(plx / 1000.0)
        name, mass, msrc = KNOWN.get(hip, (None, None, None))
        if mass is None:
            mass = mass_estimate(absm)
        rows.append((hip, x, y, z, hp, bv, mass, name, msrc))
    rows.sort(key=lambda r: r[1] ** 2 + r[2] ** 2 + r[3] ** 2)  # nearest first
    # The catalogue is split into CHUNK-star modules so a host can load one per tick: OPEN//77 meters instructions
    # per call (the same reason space.canonical propagates in slices). `out` is a directory.
    os.makedirs(out, exist_ok=True)
    chunks = [rows[i:i + CHUNK] for i in range(0, len(rows), CHUNK)]
    with open(os.path.join(out, "data_stars.lua"), "w", encoding="utf-8", newline="\n") as f:
        f.write("-- ncm-core module: space.data.stars -- GENERATED by tools/build-star-catalogue.py; do not edit.\n")
        f.write("-- Hipparcos new reduction (van Leeuwen 2007, CDS I/311), ESA: %d stars, nearest first, in %d chunk\n" % (len(rows), len(chunks)))
        f.write("-- modules space.data.stars.1 .. %d (parallel arrays: hip, x/y/z pc ICRS epoch 1991.25, hp, bv, mass Msun --\n" % len(chunks))
        f.write("-- estimated unless `named` gives a source). Published parallaxes replace Hipparcos's for: %s.\n"
                % ", ".join("HIP %d (%s)" % (h, s) for h, (p, s) in PLX_OVERRIDE.items()))
        f.write("local Core = NcmCore\nCore.define(\"space.data.stars\", function()\n    return {\n")
        f.write("        source = \"Hipparcos new reduction, van Leeuwen 2007, A&A 474, 653 (CDS I/311)\",\n")
        f.write("        count = %d,\n        chunks = %d,\n" % (len(rows), len(chunks)))
        f.write("        named = {\n")
        for r in rows:
            if r[7]:
                f.write('            [%d] = { name = "%s", massSource = "%s" },\n' % (r[0], r[7], r[8]))
        f.write("        },\n    }\nend)\n")
    for n, chunk in enumerate(chunks, 1):
        with open(os.path.join(out, "data_stars_%02d.lua" % n), "w", encoding="utf-8", newline="\n") as f:
            f.write("-- ncm-core module: space.data.stars.%d -- GENERATED by tools/build-star-catalogue.py; do not edit.\n" % n)
            f.write("local Core = NcmCore\nCore.define(\"space.data.stars.%d\", function()\n    return {\n" % n)
            for col, idx, fmt in (("hip", 0, "%d"), ("x", 1, "%.5f"), ("y", 2, "%.5f"), ("z", 3, "%.5f"),
                                  ("hp", 4, "%.2f"), ("bv", 5, "%.2f"), ("mass", 6, "%.3f")):
                f.write("        %s = {" % col)
                for i, r in enumerate(chunk):
                    if i % 40 == 0:
                        f.write("\n            ")
                    f.write(fmt % r[idx] + ",")
                f.write("\n        },\n")
            f.write("    }\nend)\n")
    # The naked-eye sky for hosts that DRAW stars (the Deep page): directions only, same rows, Hp < BRIGHT_SKY.
    bright = [r for r in rows if r[4] < BRIGHT_SKY]
    with open(os.path.join(out, "brightstars.lua"), "w", encoding="utf-8", newline="\n") as f:
        f.write("-- ncm-core module: space.data.brightstars -- GENERATED by tools/build-star-catalogue.py; do not edit.\n")
        f.write("-- The naked-eye sky (Hp < %.1f, %d stars) from the same Hipparcos rows as space.data.stars: flat\n" % (BRIGHT_SKY, len(bright)))
        f.write("-- { x, y, z, hp, ... } with x/y/z a unit ICRS direction from the Sun. For drawing, never for gravity.\n")
        f.write("local Core = NcmCore\nCore.define(\"space.data.brightstars\", function()\n    return {")
        for i, r in enumerate(bright):
            n = math.sqrt(r[1] ** 2 + r[2] ** 2 + r[3] ** 2)
            if i % 8 == 0:
                f.write("\n        ")
            f.write("%.5f,%.5f,%.5f,%.2f," % (r[1] / n, r[2] / n, r[3] / n, r[4]))
        f.write("\n    }\nend)\n")
    print("stars:", len(rows), "in", len(chunks), "chunks ->", out, "; bright sky:", len(bright))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
