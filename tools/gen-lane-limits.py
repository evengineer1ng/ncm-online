"""Generate the server-side posted-speed lane index from the game's own traffic data (L301, IDEA-885).

Source: the WolvenKit serialisation of the vanilla traffic files NCM Pace already decoded
(ncm/pace/build/road-data/all.traffic_persistent.json + all.lane_polygons.json). Every lane carries a native
`maxSpeed` in m/s: vehicle lanes are 10 / 15 / 17 (36 / 54 / 61 km/h), pedestrian lanes 1. Only vehicle lanes are kept.

Output: ncm/online/resources/ncm_speed/server/lane_limits_data.lua -- server only, never shipped to a client.
One string per speed class: lanes separated by '|', points 'x,y,z' in whole metres separated by ';', thinned to
about STEP metres. The server builds its cell index at load (core `world.speed_limits`).

Usage:  python tools/gen-lane-limits.py [--step 10]
"""
import argparse, hashlib, json, math, os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DATA = os.path.join(ROOT, "ncm", "pace", "build", "road-data")
OUT = os.path.join(ROOT, "ncm", "online", "resources", "ncm_speed", "server", "lane_limits_data.lua")
MAX_BYTES = 6 * 1024 * 1024


def thin(points, step):
    out = [points[0]]
    acc = 0.0
    for a, b in zip(points, points[1:]):
        acc += math.dist(a[:2], b[:2])
        if acc >= step:
            out.append(b)
            acc = 0.0
    if out[-1] is not points[-1]:
        out.append(points[-1])
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--step", type=float, default=10.0)
    a = ap.parse_args()
    lanes = json.load(open(os.path.join(DATA, "all.traffic_persistent.json"), encoding="utf-8"))["Data"]["RootChunk"]["data"]["lanes"]
    poly = {d["index"]: d["value"]["outline"]
            for d in json.load(open(os.path.join(DATA, "all.lane_polygons.json"), encoding="utf-8"))["Data"]["RootChunk"]["data"]}
    by = {}
    kept = pts = 0
    km = 0.0
    for i, lane in enumerate(lanes):
        speed = int(lane.get("maxSpeed") or 0)
        line = poly.get(i) or []
        if speed < 8 or len(line) < 2:
            continue
        p = [(round(v["X"]), round(v["Y"]), round(v["Z"])) for v in line]
        p = thin(p, a.step)
        dedup = [p[0]] + [q for prev, q in zip(p, p[1:]) if q != prev]
        if len(dedup) < 2:
            continue
        by.setdefault(speed, []).append(";".join(f"{x},{y},{z}" for x, y, z in dedup))
        kept += 1
        pts += len(dedup)
        km += float(lane.get("length") or 0) / 1000
    lines = [
        "-- GENERATED by tools/gen-lane-limits.py from the game's traffic lanes -- do not edit by hand. (L301, IDEA-885)",
        "-- Posted speed per vehicle lane, as the game itself cooks it (m/s). Server only: never shipped to a client.",
        "-- Decoded once at load by `world.speed_limits`.",
        "NcmLaneLimitsData = {",
    ]
    for speed in sorted(by):
        lines.append(f'  [{speed}] = "{"|".join(by[speed])}",')
    lines.append("}")
    text = "\n".join(lines) + "\n"
    size = len(text.encode("utf-8"))
    if size > MAX_BYTES:
        raise SystemExit(f"lane index is {size / 1e6:.1f} MB, over the {MAX_BYTES / 1e6:.0f} MB budget; raise --step")
    open(OUT, "w", encoding="utf-8", newline="\n").write(text)
    classes = ", ".join(f"{s} m/s: {len(v)}" for s, v in sorted(by.items()))
    print(f"{kept} vehicle lanes ({km:.0f} km), {pts} points, {size / 1e6:.2f} MB, sha256 {hashlib.sha256(text.encode()).hexdigest()[:16]}")
    print(f"classes: {classes}")
    print(f"-> {OUT}")


if __name__ == "__main__":
    main()
